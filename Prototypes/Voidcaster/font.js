  const ORDER = Object.keys(G);
  const sheets = {};
  function sheet(col) {
    if (sheets[col]) return sheets[col];
    const c = document.createElement('canvas');
    c.width = ORDER.length * 6; c.height = 7;
    const x = c.getContext('2d');
    x.fillStyle = col;
    ORDER.forEach((ch, i) => {
      G[ch].forEach((row, y) => { for (let k = 0; k < 5; k++) if (row[k] === '#') x.fillRect(i * 6 + k, y, 1, 1); });
    });
    return (sheets[col] = c);
  }
  const index = {};
  ORDER.forEach((ch, i) => { index[ch] = i; });
  function width(s, sc = 1) { return Math.max(0, String(s).length * 6 - 1) * sc; }
  function draw(ctx, s, x, y, col = '#fff', sc = 1, align = 'l', shadow = null) {
    s = String(s).toUpperCase();
    x = Math.round(x); y = Math.round(y);
    if (align === 'c') x -= Math.round(width(s, sc) / 2);
    else if (align === 'r') x -= width(s, sc);
    const draw1 = (c, ox, oy) => {
      const sh = sheet(c);
      for (let i = 0; i < s.length; i++) {
        const k = index[s[i]];
        if (k === undefined || s[i] === ' ') continue;
        ctx.drawImage(sh, k * 6, 0, 5, 7, x + ox + i * 6 * sc, y + oy, 5 * sc, 7 * sc);
      }
    };
    if (shadow) draw1(shadow, sc, sc);
    draw1(col, 0, 0);
  }
  function wrap(s, maxChars) {
    const out = []; let line = '';
    String(s).toUpperCase().split(' ').forEach((w) => {
      if (line && (line + ' ' + w).length > maxChars) { out.push(line); line = w; }
      else line = line ? line + ' ' + w : w;
    });
    if (line) out.push(line);
    return out;
  }
  return { draw, width, wrap, glyphs: ORDER };

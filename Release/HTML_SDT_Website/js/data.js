/* ── Compute grammar for each isotope ── */
const ISO = RAW.map(([Z,A,sym,stab,be,spin,abd]) => {
  const isStable = stab.toLowerCase().startsWith("stable");
  if (Z < 2) return { Z, A, sym, stable:isStable, be:be||0, spin, abd, nd:0, nt:0, valid:false };
  const nt = A - 2*Z;
  const nd = 3*Z - A - 2;
  const valid = nd >= 0 && nt >= 0;
  const total = nd + nt;
  const tf = valid ? nt / Math.max(total,1) : 0;
  const oddA = A % 2 === 1;
  const unpaired = UNPAIRED[Z] !== undefined ? UNPAIRED[Z] : -1;
  return { Z, A, sym, stable:isStable, be:be||0, spin, abd, nd, nt, valid, tf, total, oddA, unpaired };
}).filter(e => e.valid);

/* ── Classify elements: sole (mono-isotopic) vs spread (poly-isotopic) ── */
const stableCountByZ = {};
ISO.forEach(iso => {
  if (iso.stable) stableCountByZ[iso.Z] = (stableCountByZ[iso.Z] || 0) + 1;
});
ISO.forEach(iso => {
  iso.isSole = (stableCountByZ[iso.Z] || 0) === 1;
  iso.spreadCount = stableCountByZ[iso.Z] || 0;
});

/* Max abundance per element — for relative-abundance ring scaling */
const maxAbdByZ = {};
ISO.forEach(iso => {
  if (iso.abd > 0)
    maxAbdByZ[iso.Z] = Math.max(maxAbdByZ[iso.Z] || 0, iso.abd);
});

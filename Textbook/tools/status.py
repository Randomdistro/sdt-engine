"""Regenerate Textbook/PRODUCTION_STATUS.md from the files that exist.

Run from anywhere:  python Textbook/tools/status.py
A chapter is 'drafted' when volume_0V/chNN_*.md exists. Its instrument is Textbook/examples/chNN_*.cpp|py,
its pre-registration Textbook/validation/chNN_PRE_REGISTRATION.md, its runs chNN_run*_output.txt.
The last run's final line decides 'criteria met'.
"""
import csv
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
TB = os.path.dirname(HERE)
ROOT = os.path.dirname(TB)
REGISTER = os.path.join(ROOT, "Projects", "sdt-investigations", "Investigations",
                        "SDT_Textbook_Architecture_2026-10-27_2", "CHAPTER_REGISTER2.csv")


def first(pattern):
    hits = sorted(glob.glob(pattern))
    return hits[0] if hits else None


def main():
    with open(REGISTER, encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    lines = []
    total_words = 0
    done = 0
    for r in rows:
        ch = int(r["chapter"])
        vol = int(r["volume"])
        title = r["title"]
        md = first(os.path.join(TB, f"volume_{vol:02d}", f"ch{ch:02d}_*.md"))
        words = 0
        if md:
            with open(md, encoding="utf-8") as fh:
                words = len(fh.read().split())
            done += 1
            total_words += words
        inst = first(os.path.join(TB, "examples", f"ch{ch:02d}_*.cpp")) or first(
            os.path.join(TB, "examples", f"ch{ch:02d}_*.py"))
        prereg = os.path.exists(os.path.join(TB, "validation", f"ch{ch:02d}_PRE_REGISTRATION.md"))
        runs = sorted(glob.glob(os.path.join(TB, "validation", f"ch{ch:02d}_run*_output.txt")),
                      key=lambda p: int(re.search(r"run(\d+)", p).group(1)))
        verdict = "-"
        if runs:
            with open(runs[-1], encoding="utf-8", errors="replace") as fh:
                tail = fh.read().strip().splitlines()[-1:]
            met = tail and ("ALL CRITERIA MET" in tail[0] or "all pre-registered criteria met" in tail[0])
            verdict = "criteria met" if met else "NOT MET (see run)"
        lines.append(
            f"| {ch} | {vol} | {title} | {'drafted' if md else 'planned'} | {words} | "
            f"{'yes' if inst else '-'} | {'yes' if prereg else '-'} | {len(runs)} | {verdict} |")
    out = [
        "# Textbook production status",
        "",
        "Generated by `python Textbook/tools/status.py` from the files present. Do not edit by hand.",
        "",
        f"Chapters drafted: {done} of {len(rows)}. Words in drafted chapters: {total_words}.",
        "",
        "| ch | vol | title | state | words | instrument | pre-reg | runs | last run |",
        "|---|---|---|---|---|---|---|---|---|",
    ] + lines + [""]
    with open(os.path.join(TB, "PRODUCTION_STATUS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"drafted {done}/{len(rows)}, words {total_words}")


if __name__ == "__main__":
    main()
